import os
import shutil
from pathlib import Path
from datetime import datetime
from dataclasses import dataclass

import pybedtools

from flnc2.utils.custom_logger import get_logger
from flnc2.utils.exceptions import StepError
from flnc2.utils.pipeline_step import PipelineStep
from flnc2.utils.py_bedtools import remove_impure_loci

logger = get_logger()

@dataclass(frozen=True)
class FilterPredictedCodingOutput:
    bed_path: Path
    summary_path: Path
    num_final: int

class FilterPredictedCoding(PipelineStep[FilterPredictedCodingOutput]):
    def __init__(
        self,
        noncoding_bed_path: str | Path,
        coding_bed_path: str | Path,
        output_dir: str | Path,
    ):
        self.noncoding_bed_path = Path(noncoding_bed_path)
        self.coding_bed_path = Path(coding_bed_path)
        self.output_dir = Path(output_dir)

    def run(self) -> FilterPredictedCodingOutput:
        missing = [str(p) for p in (self.noncoding_bed_path, self.coding_bed_path) if not p.is_file()]
        if missing:
            raise StepError("Required file(s) not found: " + ", ".join(missing))

        self.output_dir.mkdir(parents=True, exist_ok=True)
        out_bed = self.output_dir / "pure_noncoding.bed"

        noncoding = pybedtools.BedTool(str(self.noncoding_bed_path))
        coding = pybedtools.BedTool(str(self.coding_bed_path))

        num_input = noncoding.count()
        num_coding = coding.count()
        logger.info("Input noncoding transcripts: %d", num_input)
        logger.info("Predicted-coding transcripts to exclude against: %d", num_coding)

        if num_coding == 0 or num_input == 0:
            logger.info("Nothing to filter, passing input through unchanged")
            self._atomic_copy(self.noncoding_bed_path, out_bed)
            num_notoverlap, num_overlap, num_final = num_input, 0, num_input
        else:
            result = remove_impure_loci(noncoding, coding)

            num_notoverlap = result.notoverlap.count()
            logger.info(
                "  no same-strand overlap with predicted-coding: %d (dropped %d)",
                num_notoverlap, num_input - num_notoverlap,
            )
            num_overlap = result.overlap.count()
            logger.info(
                "  overlapping predicted-coding (used to flag impure loci): %d", num_overlap,
            )

            # Write to a temp name and rename, so a crash never leaves a
            # half-written file under the final name.
            tmp = out_bed.with_suffix(".bed.tmp")
            result.pure.saveas(str(tmp))
            os.replace(tmp, out_bed)

            num_final = result.pure.count()
            logger.info(
                "  after removing loci shared with predicted-coding transcripts: %d (dropped %d)",
                num_final, num_notoverlap - num_final,
            )

        pct = 100 * num_final / num_input if num_input else 0.0
        logger.info("  Retained %d / %d transcripts (%.1f%%)", num_final, num_input, pct)
        logger.info("  BED: %s", out_bed)

        summary = self._write_summary(
            num_input=num_input,
            num_coding=num_coding,
            num_notoverlap=num_notoverlap,
            num_overlap=num_overlap,
            num_final=num_final,
        )
        return FilterPredictedCodingOutput(bed_path=out_bed, summary_path=summary, num_final=num_final)

    @staticmethod
    def _atomic_copy(src: Path, dst: Path) -> None:
        tmp = dst.with_suffix(dst.suffix + ".tmp")
        shutil.copyfile(src, tmp)
        os.replace(tmp, dst)

    def _write_summary(self, **counts: int) -> Path:
        summary_file = self.output_dir / "predicted_nonlncrna_filter_summary.tsv"
        columns = ("num_input", "num_coding", "num_notoverlap", "num_overlap", "num_final")
        with summary_file.open("w") as f:
            f.write(f"# generated by {type(self).__name__} on: "
                    f"{datetime.now().astimezone().isoformat(timespec='seconds')}\n")
            f.write("# num_input: input noncoding transcripts (before filtering associated coding loci).\n")
            f.write("# num_coding: input predicted coding transcripts.\n")
            f.write("# num_notoverlap: no same-strand overlap with predicted coding transcripts.\n")
            f.write("# num_overlap: overlapping predicted coding transcripts (used to flag impure loci).\n")
            f.write("# num_final: after removing loci shared with predicted-coding transcripts.\n")
            f.write("input\t" + "\t".join(columns) + "\n")
            f.write(self.noncoding_bed_path.name + "\t"
                    + "\t".join(str(counts[c]) for c in columns) + "\n")
        logger.info("Find a report in %s", summary_file)
        return summary_file
